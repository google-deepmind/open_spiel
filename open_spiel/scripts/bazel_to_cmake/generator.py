"""Translates OpenSpiel's BUILD files into per-package CMake files.

Contract with the hand-written root CMakeLists.txt:

* Package `p/q` gets `p/q/CMakeLists.txt`; the root package gets
  `targets.cmake`, which the root CMakeLists.txt includes. Packages without
  C++ rules get nothing. Each generated file adds the generated packages below
  it whose nearest generated ancestor it is; the hand-written files add the
  rest (top-level directories, python/pybind11).
* Target `//p/q:n` becomes CMake target `open_spiel_p_q_n` with alias
  `open_spiel::p::q::n` (root package: `open_spiel_n`, `open_spiel::n`).
  `pybind_extension` targets keep their bare name (setup.py builds `pyspiel`).
* A library with sources becomes an OBJECT library `<t>_objs` wrapped in an
  INTERFACE library `<t>` that also links `$<TARGET_OBJECTS:<t>_objs>`, so the
  objects (and their static registerers) reach every final link, transitively
  (CMake >= 3.21). This holds with or without `alwayslink`: Bazel links tests
  dynamically, so registerers in libraries without it (e.g. zerosum) run
  there too. Libraries without sources become INTERFACE libraries. Every
  non-testonly library that does not need Python is appended to the global
  property OPEN_SPIEL_OBJECT_LIBRARIES (inside its guard, see below).
* `select()` on a `config_setting` of a `bool_flag` named `build_with_<x>`
  becomes `if(OPEN_SPIEL_BUILD_WITH_<X>)`. A target needing an optional
  dependency (directly, via `target_compatible_with`, or through its deps) is
  wrapped in `if(<option>)`. pybind targets need OPEN_SPIEL_BUILD_WITH_PYTHON
  and implicitly link open_spiel_ext::pybind11.
* Platform select() keys (label_map.PLATFORM_CONDITIONS, e.g. the Windows
  constraint) become the matching CMake platform variable (`WIN32`), so a
  target incompatible with Windows is wrapped in `if(NOT WIN32)`.
* copts and features are dropped: the root sets flags per compiler.
"""

import collections
import dataclasses
import itertools
import os
import re
from typing import Any, Iterable, Optional, Sequence, Union

from open_spiel.scripts.bazel_to_cmake import build_file
from open_spiel.scripts.bazel_to_cmake import export_rules
from open_spiel.scripts.bazel_to_cmake import label_map

HEADER = "# Generated by scripts/generate_cmake.sh from BUILD. Do not edit.\n"
ROOT_OUTPUT = "targets.cmake"
PACKAGE_OUTPUT = "CMakeLists.txt"
BUILD_FILE_NAMES = ("BUILD", "BUILD.bazel")

PYTHON_OPTION = "OPEN_SPIEL_BUILD_WITH_PYTHON"
PYBIND_TARGET = "open_spiel_ext::pybind11"
OBJECT_LIBRARIES_PROPERTY = "OPEN_SPIEL_OBJECT_LIBRARIES"
SOURCE_DIR = "${open_spiel_SOURCE_DIR}"

_LIBRARY_RULES = frozenset({"cc_library", "pybind_library"})
_TEST_RULES = frozenset({"cc_test", "pybind_library_test"})
_PYBIND_RULES = frozenset(
    {"pybind_extension", "pybind_library", "pybind_library_test"})
_COMPILED_EXTENSIONS = (".c", ".cc", ".cpp")

# Attributes each C++ rule may carry. Anything else is a hard error, so that a
# new attribute is translated deliberately rather than silently ignored.
_COMMON_ATTRS = frozenset({
    "compatible_with", "copts", "data", "deprecation", "deps", "features",
    "hdrs", "licenses", "name", "srcs", "tags", "target_compatible_with",
    "testonly", "visibility",
})
_ALLOWED_ATTRS = {
    "cc_library": _COMMON_ATTRS | {"alwayslink", "linkstatic"},
    "pybind_library": _COMMON_ATTRS | {"alwayslink", "linkstatic"},
    "cc_binary": _COMMON_ATTRS | {"args"},
    "cc_test": _COMMON_ATTRS | {
        "args", "flaky", "local", "shard_count", "size", "timeout"},
    "pybind_library_test": _COMMON_ATTRS | {
        "args", "flaky", "local", "shard_count", "size", "timeout"},
    "pybind_extension": _COMMON_ATTRS,
}

# copts the generator may drop: CMake sets flags per compiler, and the root
# defines OPEN_SPIEL_BUILD_WITH_* globally for enabled options.
_DROPPABLE_COPTS = re.compile(r"-fexceptions|-DOPEN_SPIEL_BUILD_WITH_[A-Z_]+")

# Paths in `args` pointing into the source tree, in source or exported form.
_TREE_PATH = re.compile(r"(?<![\w/])(?:\w+/)*?open_spiel/([\w./-]+)")
_LOCATION = re.compile(r"\$\((?:location|rootpath|execpath) ([^)]+)\)")
_UNQUOTED_ARG = re.compile(r"[A-Za-z0-9_./=:+,@%<>${}\-]+")

# A conjunction of (CMake option, required value), sorted.
Condition = tuple[tuple[str, bool], ...]


class GenerationError(Exception):
  """Raised when the BUILD files cannot be translated."""


@dataclasses.dataclass
class Package:
  """A Bazel package and the rules it declares."""

  path: str
  build_path: str
  rules: list[build_file.Rule]

  @property
  def cc_rules(self) -> list[build_file.Rule]:
    """The rules translated to CMake."""
    return [r for r in self.rules if r.kind in build_file.CC_RULES]

  @property
  def output(self) -> str:
    """Generated file path relative to the OpenSpiel root."""
    return os.path.join(self.path, PACKAGE_OUTPUT) if self.path else ROOT_OUTPUT


@dataclasses.dataclass(frozen=True)
class _Analysis:
  """Derived facts about one C++ target.

  Attributes:
    guard: (CMake variable, required value) pairs the target needs.
    skip: If set, why CMake does not build the target.
  """

  guard: frozenset[tuple[str, bool]]
  skip: Optional[str]


def cmake_name(package: str, name: str) -> str:
  """CMake target name of `//package:name`."""
  parts = ["open_spiel"] + (package.split("/") if package else []) + [name]
  return re.sub(r"[^A-Za-z0-9_.+-]", "_", "_".join(parts))


def alias_name(package: str, name: str) -> str:
  """Namespaced CMake alias of `//package:name`."""
  parts = ["open_spiel"] + (package.split("/") if package else []) + [name]
  return "::".join(parts)


def _condition_text(condition: Condition) -> str:
  return " AND ".join(o if value else f"NOT {o}" for o, value in condition)


def _quote(arg: str) -> str:
  if _UNQUOTED_ARG.fullmatch(arg):
    return arg
  escaped = arg.replace("\\", "\\\\").replace('"', '\\"')
  return f'"{escaped}"'


def _command(name: str, head: Sequence[str], items: Sequence[str] = (),
             indent: str = "") -> list[str]:
  """Formats a CMake command, one list item per line."""
  if not items:
    return [f"{indent}{name}({' '.join(head)})"]
  lines = [f"{indent}{name}({' '.join(head)}"]
  lines.extend(f"{indent}  {item}" for item in items)
  lines.append(f"{indent})")
  return lines


def _wrap(condition: Condition, lines: list[str], indent: str) -> list[str]:
  """Wraps already-indented `lines` in `if(condition)` unless it is empty."""
  if not condition:
    return lines
  return ([f"{indent}if({_condition_text(condition)})"] + lines +
          [f"{indent}endif()"])


class Workspace:
  """All exported packages under an OpenSpiel source root."""

  def __init__(self, root: str, check_sources: bool = True):
    """Loads every exported package below `root`.

    Args:
      root: The OpenSpiel directory (the one holding spiel.h).
      check_sources: Whether to require that source files exist. Off when
        only the BUILD files are at hand.

    Raises:
      GenerationError: If a BUILD file cannot be evaluated.
    """
    self.root = root
    self.check_sources = check_sources
    self.packages: dict[str, Package] = {}
    for path in self._find_packages():
      self.packages[path] = self._load_package(path)
    self.rules: dict[tuple[str, str], build_file.Rule] = {}
    for package in self.packages.values():
      for rule in package.rules:
        key = (package.path, rule.name)
        if key in self.rules:
          raise GenerationError(
              f"{package.build_path}: duplicate target {rule.name}")
        self.rules[key] = rule
    self._analysis: dict[tuple[str, str], _Analysis] = {}
    self._in_progress: set[tuple[str, str]] = set()
    self._test_name_counts: Optional[collections.Counter[str]] = None
    # Targets CMake does not build, filled in by generate().
    self.skipped: list[str] = []

  # Loading.

  def _ignored_dirs(self) -> set[str]:
    """Directories `.bazelignore` (exported repository only) tells Bazel to skip."""
    repo_root = os.path.dirname(os.path.abspath(self.root))
    path = os.path.join(repo_root, ".bazelignore")
    if not os.path.exists(path):
      return set()
    with open(path) as f:
      entries = [line.strip() for line in f]
    return {os.path.normpath(os.path.join(repo_root, e))
            for e in entries if e and not e.startswith("#")}

  def _find_packages(self) -> list[str]:
    """Package paths below the root that the export keeps, sorted."""
    ignored = self._ignored_dirs()
    packages = []
    for dirpath, dirnames, filenames in os.walk(self.root):
      rel = os.path.relpath(dirpath, self.root)
      rel = "" if rel == "." else rel
      dirnames[:] = sorted(
          d for d in dirnames if not d.startswith(".") and
          os.path.normpath(os.path.join(dirpath, d)) not in ignored)
      if rel and any(m in filenames or m in dirnames for m in (
          ".git", "MODULE.bazel", "WORKSPACE", "WORKSPACE.bazel")):
        dirnames[:] = []  # A nested repository (e.g. a vendored dependency).
        continue
      found = [f for f in BUILD_FILE_NAMES if f in filenames]
      if not found:
        continue
      if len(found) > 1:
        raise GenerationError(f"{dirpath} has both BUILD and BUILD.bazel")
      if export_rules.is_excluded(os.path.join(rel, "BUILD")):
        continue
      packages.append(rel)
    return sorted(packages)

  def _load_package(self, path: str) -> Package:
    directory = os.path.join(self.root, path)
    name = next(f for f in BUILD_FILE_NAMES
                if os.path.exists(os.path.join(directory, f)))
    filename = os.path.join(path, name)
    with open(os.path.join(directory, name)) as f:
      text = f.read()
    try:
      rules = build_file.evaluate(text, path, directory, filename)
    except build_file.Error as e:
      raise GenerationError(str(e)) from e
    return Package(path=path, build_path=filename, rules=rules)

  # Labels and conditions.

  def _where(self, rule: build_file.Rule) -> str:
    return f"{self.packages[rule.package].build_path}:{rule.name}"

  def resolve(self, label: str, package: str,
              context: str) -> Union[tuple[str, str], label_map.ExternalLabel]:
    """Resolves a label to an OpenSpiel (package, name) or an external entry."""
    if label.startswith(":"):
      return package, label[1:]
    if not label.startswith(("//", "@")):
      return package, label
    if label_map.is_open_spiel(label):
      return label_map.open_spiel_package_and_name(label)
    entry = label_map.lookup(label)
    if entry is None:
      raise GenerationError(
          f"{context}: unknown label {label}; add it to "
          "scripts/bazel_to_cmake/label_map.py")
    return entry

  def _rule_at(self, key: tuple[str, str], context: str) -> build_file.Rule:
    if key not in self.rules:
      raise GenerationError(
          f"{context}: no target //{key[0]}:{key[1]} in exported packages")
    return self.rules[key]

  def _option(self, key: str, package: str, context: str) -> tuple[str, bool]:
    """Maps a select() key to (CMake option, value it selects)."""
    if key in label_map.PLATFORM_CONDITIONS:
      return label_map.PLATFORM_CONDITIONS[key], True
    resolved = self.resolve(key, package, context)
    if isinstance(resolved, label_map.ExternalLabel):
      raise GenerationError(f"{context}: select() key {key} is not ours")
    setting = self._rule_at(resolved, context)
    flags = setting.attrs.get("flag_values", {})
    if setting.kind != "config_setting" or len(flags) != 1:
      raise GenerationError(
          f"{context}: select() key {key} must be a config_setting with one "
          "flag_values entry")
    (flag_label, value), = flags.items()
    flag_key = self.resolve(flag_label, setting.package, context)
    if isinstance(flag_key, label_map.ExternalLabel):
      raise GenerationError(f"{context}: flag {flag_label} is not ours")
    flag = self._rule_at(flag_key, context)
    if flag.kind != "bool_flag" or not flag.name.startswith("build_with_"):
      raise GenerationError(
          f"{context}: {flag_label} must be a bool_flag named build_with_<x>")
    text = str(value).lower()
    if text not in ("true", "false", "1", "0"):
      raise GenerationError(f"{context}: bad flag value {value!r}")
    return "OPEN_SPIEL_" + flag.name.upper(), text in ("true", "1")

  def conditional_items(self, rule: build_file.Rule,
                        attr: str) -> list[tuple[Condition, Any]]:
    """Flattens a (possibly select()ed) list attribute."""
    value = rule.attrs.get(attr)
    context = f"{self._where(rule)}: {attr}"
    if value is None:
      return []
    if isinstance(value, build_file.GlobResult):
      raise GenerationError(f"{context}: glob() is not supported in C++ rules")
    if isinstance(value, list):
      return [((), item) for item in value]
    if not isinstance(value, build_file.Selectable):
      raise GenerationError(f"{context}: unsupported value {value!r}")
    items = []
    for part in value.parts:
      if isinstance(part, list):
        items.extend(((), item) for item in part)
        continue
      branches = [(k, v) for k, v in part.branches
                  if k != label_map.DEFAULT_CONDITION]
      default = [v for k, v in part.branches
                 if k == label_map.DEFAULT_CONDITION]
      if len(branches) > 1:
        raise GenerationError(
            f"{context}: select() with more than one non-default key")
      if not branches:
        items.extend(((), item) for item in (default[0] if default else []))
        continue
      (key, selected), = branches
      option, enabled = self._option(key, rule.package, context)
      items.extend((((option, enabled),), item) for item in selected)
      for item in default[0] if default else []:
        items.append((((option, not enabled),), item))
    return items

  # Analysis.

  def analyze(self, key: tuple[str, str]) -> _Analysis:
    """Computes which options a C++ target needs and whether CMake skips it."""
    if key in self._analysis:
      return self._analysis[key]
    if key in self._in_progress:
      raise GenerationError(f"Dependency cycle through //{key[0]}:{key[1]}")
    self._in_progress.add(key)
    try:
      result = self._analyze(key)
    finally:
      self._in_progress.discard(key)
    self._analysis[key] = result
    return result

  def _analyze(self, key: tuple[str, str]) -> _Analysis:
    """Implements `analyze` once cycles and memoization are handled."""
    rule = self.rules[key]
    context = self._where(rule)
    guard: set[tuple[str, bool]] = set()
    skip = None
    if rule.kind in _PYBIND_RULES:
      guard.add((PYTHON_OPTION, True))
    for condition, item in self.conditional_items(rule,
                                                  "target_compatible_with"):
      if item not in label_map.INCOMPATIBLE_LABELS:
        raise GenerationError(
            f"{context}: target_compatible_with only supports "
            "select({<setting>: [incompatible]}) with an empty other branch"
        )
      if not condition:
        skip = "is marked incompatible"
      elif len(condition) == 1:
        # Incompatible when the variable has this value: require the other.
        option, value = condition[0]
        guard.add((option, not value))
      else:
        raise GenerationError(
            f"{context}: target_compatible_with may depend on one condition"
        )
    for condition, label in self.conditional_items(rule, "deps"):
      resolved = self.resolve(label, rule.package, context)
      if isinstance(resolved, label_map.ExternalLabel):
        if resolved.skip:
          if condition:
            raise GenerationError(
                f"{context}: conditional dep {label} is not built by CMake")
          skip = skip or resolved.skip
        elif resolved.option and not condition:
          guard.add((resolved.option, True))
        continue
      dep = self._rule_at(resolved, context)
      if dep.kind not in _LIBRARY_RULES:
        raise GenerationError(
            f"{context}: dep {label} is a {dep.kind}, not a library")
      dep_analysis = self.analyze(resolved)
      if dep_analysis.skip:
        if condition:
          raise GenerationError(
              f"{context}: conditional dep {label} is not built by CMake")
        skip = skip or dep_analysis.skip
      if not condition:
        guard |= dep_analysis.guard
    return _Analysis(guard=frozenset(guard), skip=skip)

  # Emission.

  def _dep_edges(
      self, rule: build_file.Rule, guard: frozenset[tuple[str, bool]]
  ) -> dict[Condition, list[str]]:
    """CMake link items of a target, grouped by the condition they need."""
    context = self._where(rule)
    edges: dict[Condition, list[str]] = collections.defaultdict(list)
    for condition, label in self.conditional_items(rule, "deps"):
      resolved = self.resolve(label, rule.package, context)
      needed = dict(condition)
      if isinstance(resolved, label_map.ExternalLabel):
        target = resolved.cmake
        if resolved.option:
          extra = {(resolved.option, True)} - guard
        else:
          extra = set()
      else:
        target = alias_name(*resolved)
        extra = self.analyze(resolved).guard - guard
      for option, value in sorted(extra):
        if option in needed and needed[option] != value:
          raise GenerationError(
              f"{context}: dep {label} needs {option} "
              f"{'ON' if value else 'OFF'} but is selected otherwise"
          )
        needed[option] = value
      if target is None:
        continue
      key = tuple(sorted(needed.items()))
      if target not in edges[key]:
        edges[key].append(target)
    if rule.kind in _PYBIND_RULES and PYBIND_TARGET not in edges[()]:
      edges[()].append(PYBIND_TARGET)
    return edges

  def _file_path(self, rule: build_file.Rule, item: str, attr: str) -> str:
    """Path of a source file as written in the package's CMake file."""
    context = f"{self._where(rule)}: {attr}"
    if not isinstance(item, str):
      raise GenerationError(f"{context}: unsupported value {item!r}")
    package, name = self._split_file_label(rule, item, context)
    if (package, name) in self.rules:
      raise GenerationError(
          f"{context}: {item} is a target; only source files are supported")
    rel = os.path.join(package, name)
    if export_rules.is_excluded(rel):
      raise GenerationError(
          f"{context}: {item} is not exported; put the target in a "
          "GOOGLE-INTERNAL block")
    if self.check_sources and not os.path.isfile(os.path.join(self.root, rel)):
      raise GenerationError(f"{context}: {item} does not exist")
    if package == rule.package:
      return name
    return f"{SOURCE_DIR}/{rel}"

  def _split_file_label(self, rule: build_file.Rule, item: str,
                        context: str) -> tuple[str, str]:
    if item.startswith(":"):
      return rule.package, item[1:]
    if item.startswith(("//", "@")):
      if not label_map.is_open_spiel(item):
        raise GenerationError(f"{context}: external file {item}")
      return label_map.open_spiel_package_and_name(item)
    return rule.package, item

  def _sources(self, rule: build_file.Rule) -> dict[Condition, list[str]]:
    sources: dict[Condition, list[str]] = collections.defaultdict(list)
    for attr in ("srcs", "hdrs"):
      for condition, item in self.conditional_items(rule, attr):
        sources[condition].append(self._file_path(rule, item, attr))
    return sources

  def _check_copts(self, rule: build_file.Rule) -> None:
    value = rule.attrs.get("copts")
    if isinstance(value, build_file.Opaque):
      return
    for _, item in self.conditional_items(rule, "copts"):
      if not isinstance(item, str) or not _DROPPABLE_COPTS.fullmatch(item):
        raise GenerationError(
            f"{self._where(rule)}: copt {item!r} has no CMake translation")

  def _args(self, rule: build_file.Rule) -> list[str]:
    """Translates test args, mapping repository paths to CMake paths."""
    context = f"{self._where(rule)}: args"
    value = rule.attrs.get("args", [])
    if not isinstance(value, list):
      raise GenerationError(f"{context}: select() is not supported")
    result = []
    for arg in value:
      arg = _LOCATION.sub(
          lambda m: self._location(rule, m.group(1), context), arg)
      arg = _TREE_PATH.sub(lambda m: self._tree_path(m.group(1)), arg)
      result.append(_quote(arg))
    return result

  def _location(self, rule: build_file.Rule, label: str, context: str) -> str:
    package, name = self._split_file_label(rule, label, context)
    return self._tree_path(os.path.join(package, name))

  def _tree_path(self, rel: str) -> str:
    package, name = os.path.split(rel)
    target = self.rules.get((package, name))
    if target is not None and target.kind == "cc_binary":
      return f"$<TARGET_FILE:{cmake_name(package, name)}>"
    return f"{SOURCE_DIR}/{rel}"

  def _emit_target(self, rule: build_file.Rule) -> list[str]:
    """CMake lines for one C++ target (unindented, unguarded)."""
    allowed = _ALLOWED_ATTRS[rule.kind]
    unknown = sorted(set(rule.attrs) - allowed)
    if unknown:
      raise GenerationError(
          f"{self._where(rule)}: unsupported attributes {unknown}")
    self._check_copts(rule)
    analysis = self.analyze((rule.package, rule.name))
    if analysis.skip:
      self.skipped.append(f"{self._where(rule)} ({analysis.skip})")
      return [f"# {rule.kind} {rule.name}: not built by CMake "
              f"({analysis.skip})."]
    sources = self._sources(rule)
    edges = self._dep_edges(rule, analysis.guard)
    unconditional = sources.pop((), [])
    conditional = sorted(sources.items())
    name = cmake_name(rule.package, rule.name)
    lines: list[str] = []

    def add_sources(target: str) -> None:
      for condition, files in conditional:
        lines.extend(_wrap(condition, _command(
            "target_sources", [target, "PRIVATE"], files, "  "), ""))

    def link(target: str, visibility: str) -> None:
      for condition, targets in sorted(edges.items()):
        if not targets:
          continue
        indent = "  " if condition else ""
        lines.extend(_wrap(condition, _command(
            "target_link_libraries", [target, visibility], targets, indent),
                           ""))

    if rule.kind in _LIBRARY_RULES:
      if any(f.endswith(_COMPILED_EXTENSIONS) for f in unconditional):
        objects = f"{name}_objs"
        lines += _command("add_library", [objects, "OBJECT"], unconditional)
        add_sources(objects)
        link(objects, "PUBLIC")
        lines += _command("add_library", [name, "INTERFACE"])
        lines += _command("target_link_libraries", [name, "INTERFACE"],
                          [objects, f"$<TARGET_OBJECTS:{objects}>"])
      elif any(f.endswith(_COMPILED_EXTENSIONS)
               for f in itertools.chain.from_iterable(sources.values())):
        raise GenerationError(
            f"{self._where(rule)}: libraries whose compiled sources are all "
            "conditional are unsupported")
      else:
        lines += _command("add_library", [name, "INTERFACE"])
        link(name, "INTERFACE")
      lines += _command(
          "add_library", [alias_name(rule.package, rule.name), "ALIAS", name])
      if (
          not rule.attrs.get("testonly")
          and (PYTHON_OPTION, True) not in analysis.guard
      ):
        lines += _command("set_property", [
            "GLOBAL", "APPEND", "PROPERTY", OBJECT_LIBRARIES_PROPERTY, name])
    elif rule.kind == "pybind_extension":
      lines += _command("add_library", [rule.name, "MODULE"], unconditional)
      add_sources(rule.name)
      link(rule.name, "PRIVATE")
    else:
      lines += _command("add_executable", [name], unconditional)
      add_sources(name)
      if rule.kind == "cc_binary":
        lines += _command("set_target_properties",
                          [name, "PROPERTIES", "OUTPUT_NAME", rule.name])
      link(name, "PRIVATE")
      if rule.kind in _TEST_RULES:
        lines += _command(
            "add_test",
            ["NAME", self.test_name(rule), "COMMAND", name] + self._args(rule))
    guard = tuple(sorted(analysis.guard))
    if guard:
      lines = _wrap(guard, ["  " + l if l else l for l in lines], "")
    return lines

  def test_name(self, rule: build_file.Rule) -> str:
    """CTest name: the bare name, package-qualified if several tests share it."""
    if self._test_name_counts is None:
      tests = [r for r in self.rules.values() if r.kind in _TEST_RULES]
      self._test_name_counts = collections.Counter(r.name for r in tests)
    if self._test_name_counts[rule.name] > 1 and rule.package:
      return f"{rule.package}/{rule.name}"
    return rule.name

  def _check_unique_names(self) -> None:
    """Fails if two targets would get the same CMake target or test name."""
    seen: dict[str, str] = {}
    for package in self.packages.values():
      for rule in package.cc_rules:
        where = self._where(rule)
        names = []
        if rule.kind == "pybind_extension":
          names.append(("target", rule.name))
        else:
          names.append(("target", cmake_name(rule.package, rule.name)))
          names.append(("target", cmake_name(rule.package, rule.name) +
                        "_objs"))
        if rule.kind in _TEST_RULES:
          names.append(("test", self.test_name(rule)))
        for kind, name in names:
          key = f"{kind} {name}"
          if key in seen:
            raise GenerationError(
                f"{where}: CMake {kind} name {name} collides with {seen[key]}")
          seen[key] = where

  def generated_packages(self) -> list[Package]:
    """Packages that get a generated CMake file."""
    return [p for p in self.packages.values() if p.cc_rules]

  def subdirectories(self, package: str) -> list[str]:
    """Generated packages that `package`'s generated file adds."""
    generated = {p.path for p in self.generated_packages()}
    children = []
    for path in sorted(generated):
      if not path or path == package:
        continue
      parent = os.path.dirname(path)
      while parent and parent not in generated:
        parent = os.path.dirname(parent)
      if parent == package and package:
        children.append(os.path.relpath(path, package))
    return children

  def generate(self) -> dict[str, str]:
    """Returns {output path relative to root: contents} for all packages."""
    self._check_unique_names()
    outputs = {}
    errors = []
    for package in self.generated_packages():
      blocks = []
      for rule in package.cc_rules:
        try:
          blocks.append(self._emit_target(rule))
        except GenerationError as e:
          errors.append(str(e))
      subdirs = self.subdirectories(package.path)
      if subdirs:
        blocks.append([f"add_subdirectory({d})" for d in subdirs])
      body = "\n\n".join("\n".join(block) for block in blocks)
      outputs[package.output] = f"{HEADER}\n{body}\n"
    if errors:
      raise GenerationError("\n".join(dict.fromkeys(errors)))
    return outputs


def find_generated_files(root: str) -> list[str]:
  """Existing files under `root` that carry the generated-file header."""
  found = []
  for dirpath, dirnames, filenames in os.walk(root):
    dirnames[:] = sorted(d for d in dirnames if not d.startswith("."))
    for filename in filenames:
      if filename not in (PACKAGE_OUTPUT, ROOT_OUTPUT):
        continue
      path = os.path.join(dirpath, filename)
      with open(path) as f:
        if f.readline() == HEADER:
          found.append(os.path.relpath(path, root))
  return sorted(found)


def diff_outputs(root: str, outputs: dict[str, str],
                 stale_candidates: Iterable[str]) -> list[str]:
  """Lists generated files that differ from `outputs` (or should not exist)."""
  problems = []
  for rel, contents in sorted(outputs.items()):
    path = os.path.join(root, rel)
    if not os.path.exists(path):
      problems.append(f"missing: {rel}")
      continue
    with open(path) as f:
      if f.read() != contents:
        problems.append(f"stale: {rel}")
  for rel in stale_candidates:
    if rel not in outputs:
      problems.append(f"no longer generated: {rel}")
  return problems
